import type { NuxtPage } from '@nuxt/schema'
import type { ManifestRouteParam } from '../runtime/shared/types'

export interface FlatRoute {
  /** Full Nuxt route path, e.g. `/users/:id()`. */
  path: string
  /** Page files mounted for this route: every parent page plus the leaf. */
  files: string[]
}

export interface CompiledRoute {
  re: string
  params: ManifestRouteParam[]
  score: number[]
}

function joinPath(parent: string, child: string): string {
  if (child.startsWith('/')) return child
  if (!child) return parent || '/'
  return `${parent.replace(/\/+$/, '')}/${child}`
}

/**
 * Flattens Nuxt's nested page tree. A child route mounts its parent pages too,
 * so its file list is the whole chain. A route path reached by several records
 * (a parent and its `''` child) is merged.
 */
export function flattenPages(pages: NuxtPage[]): FlatRoute[] {
  const byPath = new Map<string, FlatRoute>()
  const visit = (list: NuxtPage[], parentPath: string, parentFiles: string[]) => {
    for (const page of list) {
      const path = joinPath(parentPath, page.path)
      const files = page.file ? [...parentFiles, page.file] : [...parentFiles]
      const existing = byPath.get(path)
      if (existing) {
        for (const file of files) if (!existing.files.includes(file)) existing.files.push(file)
      }
      else if (!page.redirect) {
        byPath.set(path, { path, files: [...files] })
      }
      if (page.children?.length) visit(page.children, path, files)
    }
  }
  visit(pages, '', [])
  return [...byPath.values()]
}

const PARAM_RE = /:(\w+)(?:\(((?:\\.|[^\\()])*)\))?([?*+])?/g
const DEFAULT_PARAM = '[^/]+'

/** Leftover route syntax this matcher would silently treat as literal text. */
const UNKNOWN_SYNTAX = /[():*?+]/

function escapeRegExp(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\/]/g, '\\$&')
}

/**
 * Compiles a vue-router path as generated by Nuxt (`/users/:id()`,
 * `/:slug(.*)*`, `/posts/:id?`, `/a-:b()`) into a case-insensitive RegExp
 * source with a trailing-slash-tolerant end, like vue-router's defaults.
 * Returns `null` for syntax this matcher does not understand.
 */
export function compileRoutePath(path: string): CompiledRoute | null {
  const segments = path.split('/').filter(Boolean)
  const params: ManifestRouteParam[] = []
  const score: number[] = []
  let body = ''

  for (const segment of segments) {
    const tokens = [...segment.matchAll(PARAM_RE)]
    if (tokens.length === 0) {
      if (UNKNOWN_SYNTAX.test(segment)) return null
      body += `/${escapeRegExp(segment)}`
      score.push(4)
      continue
    }
    const whole = tokens.length === 1 && tokens[0]![0] === segment ? tokens[0]! : null
    if (whole) {
      const [, name, inner, modifier] = whole
      const pattern = inner || DEFAULT_PARAM
      if (/\((?!\?)/.test(pattern)) return null // capturing groups would shift param indexes
      if (modifier === '?') {
        body += `(?:/(${pattern}))?`
        params.push({ name: name!, repeat: false })
        score.push(1)
      }
      else if (modifier === '*' || modifier === '+') {
        const unit = `(?:${pattern})`
        const repeated = `${unit}(?:/${unit})*`
        body += modifier === '*' ? `(?:/(${repeated}))?` : `/(${repeated})`
        params.push({ name: name!, repeat: true })
        score.push(0)
      }
      else {
        body += `/(${pattern})`
        params.push({ name: name!, repeat: false })
        score.push(2)
      }
      continue
    }
    // Static text mixed with params, e.g. `post-:id()`; modifiers are not supported here.
    let cursor = 0
    let part = '/'
    for (const token of tokens) {
      const [raw, name, inner, modifier] = token
      if (modifier) return null
      const pattern = inner || DEFAULT_PARAM
      if (/\((?!\?)/.test(pattern)) return null
      part += escapeRegExp(segment.slice(cursor, token.index)) + `(${pattern})`
      params.push({ name: name!, repeat: false })
      cursor = token.index! + raw.length
    }
    for (const literal of segment.split(PARAM_RE).filter((_, i) => i % 4 === 0)) {
      if (UNKNOWN_SYNTAX.test(literal)) return null
    }
    part += escapeRegExp(segment.slice(cursor))
    body += part
    score.push(3)
  }

  return { re: `^${body}/?$`, params, score }
}

/** Sort comparator: more specific routes first (static > param > optional > catch-all). */
export function compareRouteScore(a: number[], b: number[]): number {
  const length = Math.max(a.length, b.length)
  for (let i = 0; i < length; i++) {
    const diff = (b[i] ?? -1) - (a[i] ?? -1)
    if (diff !== 0) return diff
  }
  return 0
}
